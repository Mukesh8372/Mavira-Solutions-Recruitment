/**
 * Resume file rules shared by the apply form (browser), the apply action (server),
 * the download route and the tests. No `server-only` and no Node imports.
 */

export const RESUME_MAX_BYTES = 2 * 1024 * 1024; // 2 MB
export const RESUME_MAX_LABEL = "2 MB";

export const RESUME_EXTENSIONS = ["pdf", "docx", "doc"] as const;
export type ResumeExt = (typeof RESUME_EXTENSIONS)[number];

export const RESUME_MIME_BY_EXT: Record<ResumeExt, string> = {
  pdf: "application/pdf",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  doc: "application/msword",
};

/** The `accept` attribute for the file input. */
export const RESUME_ACCEPT = ".pdf,.docx,.doc";

export const RESUME_TYPE_ERROR = `Upload a PDF or Word file (.pdf, .docx, .doc) under ${RESUME_MAX_LABEL}.`;

/** Object keys are generated by the app: `resumes/<32 hex>.<ext>`. */
export const RESUME_KEY_RE = /^resumes\/[a-f0-9]{32}\.(pdf|docx|doc)$/;

export function isValidResumeKey(key: string): boolean {
  return RESUME_KEY_RE.test(key);
}

export function resumeExtFromKey(key: string): ResumeExt | null {
  const m = RESUME_KEY_RE.exec(key);
  return m ? (m[1] as ResumeExt) : null;
}

/** The lowercased last extension when it is an allowed resume type, else null. */
export function resumeExtFromFileName(name: string): ResumeExt | null {
  const dot = name.lastIndexOf(".");
  if (dot < 0) return null;
  const ext = name.slice(dot + 1).toLowerCase();
  return (RESUME_EXTENSIONS as readonly string[]).includes(ext) ? (ext as ResumeExt) : null;
}

function randomHex32(): string {
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
}

export function newResumeKey(ext: ResumeExt, hex32 = randomHex32()): string {
  return `resumes/${hex32}.${ext}`;
}

function startsWith(bytes: Uint8Array, signature: number[]): boolean {
  if (bytes.length < signature.length) return false;
  return signature.every((b, i) => bytes[i] === b);
}

function includesAscii(bytes: Uint8Array, text: string): boolean {
  const needle = Array.from(text, (c) => c.charCodeAt(0));
  outer: for (let i = 0; i + needle.length <= bytes.length; i++) {
    for (let j = 0; j < needle.length; j++) {
      if (bytes[i + j] !== needle[j]) continue outer;
    }
    return true;
  }
  return false;
}

const PDF_SIG = [0x25, 0x50, 0x44, 0x46, 0x2d]; // %PDF-
const ZIP_SIG = [0x50, 0x4b, 0x03, 0x04]; // PK\x03\x04
const OLE_SIG = [0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1]; // legacy .doc container

/**
 * Detects the real file kind from its bytes, ignoring the name and the browser's MIME type.
 * A .docx must be a ZIP that contains Word's parts; a plain ZIP renamed .docx returns null.
 * Returns null for anything else, including inputs shorter than 8 bytes.
 */
export function detectResumeKind(bytes: Uint8Array): ResumeExt | null {
  if (bytes.length < 8) return null;
  if (startsWith(bytes, PDF_SIG)) return "pdf";
  if (startsWith(bytes, OLE_SIG)) return "doc";
  if (startsWith(bytes, ZIP_SIG)) {
    return includesAscii(bytes, "[Content_Types].xml") && includesAscii(bytes, "word/") ? "docx" : null;
  }
  return null;
}

/**
 * A file name safe for a Content-Disposition header: no path parts, control characters,
 * quotes or backslashes; always ends in the detected extension; at most 120 characters.
 */
export function safeDownloadName(originalName: string, ext: ResumeExt): string {
  const base = originalName
    .split(/[\\/]/)
    .pop()!
    .replace(/\.[^.]*$/, "")
    .replace(/[\x00-\x1f\x7f"\;]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 120 - ext.length - 1);
  return `${base || "resume"}.${ext}`;
}
